struct PixelBufferView: NSViewRepresentable {
    let pixelBuffer: CVPixelBuffer

    func makeNSView(context: Context) -> NSImageView {
        let v = NSImageView()
        v.imageScaling = .scaleProportionallyUpOrDown
        v.imageAlignment = .alignCenter
        v.wantsLayer = true
        return v
    }

    func updateNSView(_ nsView: NSImageView, context: Context) {
        let ciImage = CIImage(cvPixelBuffer: pixelBuffer)
        let rep = NSCIImageRep(ciImage: ciImage)
        let img = NSImage(size: rep.size)
        img.addRepresentation(rep)
        nsView.image = img
    }
}


final class NearestNeighborNSImageView: NSImageView {
    override func draw(_ dirtyRect: NSRect) {
        NSGraphicsContext.current?.imageInterpolation = .none
        super.draw(dirtyRect)
    }
}

struct PatternView: NSViewRepresentable {
    let pattern: NSImage
    var colormap: Colormap = .gray

    func makeNSView(context: Context) -> NearestNeighborNSImageView {
        let v = NearestNeighborNSImageView()
        v.imageScaling = .scaleProportionallyUpOrDown
        v.imageAlignment = .alignCenter
        return v
    }

    func updateNSView(_ nsView: NearestNeighborNSImageView, context: Context) {
        nsView.image = colormap == .gray ? pattern : (pattern.applyingColormap(colormap) ?? pattern)
    }
}

extension NSImage {
    /// Maps an 8-bit grayscale image through a 256-entry colormap.
    func applyingColormap(_ cmap: Colormap) -> NSImage? {
        var rect = CGRect(origin: .zero, size: size)
        guard let cg = cgImage(forProposedRect: &rect, context: nil, hints: nil) else { return nil }
        let w = cg.width, h = cg.height
        // Render into an 8-bit gray buffer regardless of the source's format.
        var gray = [UInt8](repeating: 0, count: w * h)
        let ok = gray.withUnsafeMutableBytes { buf -> Bool in
            guard let ctx = CGContext(data: buf.baseAddress, width: w, height: h,
                                      bitsPerComponent: 8, bytesPerRow: w,
                                      space: CGColorSpaceCreateDeviceGray(),
                                      bitmapInfo: CGImageAlphaInfo.none.rawValue) else { return false }
            ctx.draw(cg, in: CGRect(x: 0, y: 0, width: w, height: h))
            return true
        }
        guard ok else { return nil }
        let lut = cmap.lut
        var rgba = [UInt8](repeating: 255, count: w * h * 4)
        for i in 0..<(w * h) {
            let c = lut[Int(gray[i])]
            rgba[i * 4]     = UInt8((c >> 16) & 0xFF)
            rgba[i * 4 + 1] = UInt8((c >> 8) & 0xFF)
            rgba[i * 4 + 2] = UInt8(c & 0xFF)
        }
        guard let provider = CGDataProvider(data: Data(rgba) as CFData),
              let out = CGImage(width: w, height: h, bitsPerComponent: 8, bitsPerPixel: 32,
                                bytesPerRow: w * 4, space: CGColorSpaceCreateDeviceRGB(),
                                bitmapInfo: CGBitmapInfo(rawValue: CGImageAlphaInfo.noneSkipLast.rawValue),
                                provider: provider, decode: nil, shouldInterpolate: false,
                                intent: .defaultIntent) else { return nil }
        return NSImage(cgImage: out, size: size)
    }
}



enum Colormap: String, CaseIterable, Identifiable, Sendable {
    case viridis = "Viridis"
    case inferno = "Inferno"
    case magma = "Magma"
    case plasma = "Plasma"
    case turbo = "Turbo"
    case twilight = "Twilight"   // cyclic — good for phase
    case gray = "Gray"

    var id: String { rawValue }

    var isCyclic: Bool { self == .twilight }

    /// 256-entry packed 0xRRGGBB lookup table.
    var lut: [UInt32] {
        switch self {
        case .viridis: ColormapData.viridis
        case .inferno: ColormapData.inferno
        case .magma: ColormapData.magma
        case .plasma: ColormapData.plasma
        case .turbo: ColormapData.turbo
        case .twilight: ColormapData.twilight
        case .gray: ColormapData.gray
        }
    }
}


